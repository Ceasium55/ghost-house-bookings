import { serve } from "https://deno.land/std@0.168.0/http/server.ts";
import { createClient } from "https://esm.sh/@supabase/supabase-js@2";

const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version',
};

const CATEGORY_CAPACITY = 16;
const VALID_CATEGORIES = ['s1-s3', 's4-s7'];

serve(async (req) => {
  if (req.method === 'OPTIONS') {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const supabase = createClient(
      Deno.env.get('SUPABASE_URL')!,
      Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!
    );

    const result: Record<string, { taken: number; available: number; capacity: number }> = {};
    for (const category of VALID_CATEGORIES) {
      const { count } = await supabase
        .from('chess_registrations')
        .select('*', { count: 'exact', head: true })
        .eq('category', category);
      const taken = count ?? 0;
      result[category] = { taken, available: Math.max(0, CATEGORY_CAPACITY - taken), capacity: CATEGORY_CAPACITY };
    }

    return new Response(JSON.stringify(result), {
      status: 200, headers: { ...corsHeaders, 'Content-Type': 'application/json' },
    });
  } catch (err) {
    console.error('Error:', err);
    return new Response(JSON.stringify({ error: 'Internal server error' }), {
      status: 500, headers: { ...corsHeaders, 'Content-Type': 'application/json' },
    });
  }
});
